function resume_K = exportdata2(session, P, A, config, namefull)
% = exportdata : une ligne de résumé pour ce K, écrite dans
% <session>\kXX\analysis.xlsx et gardée dans assemblees.mat (resume_K).
% Changements :
%  - analysisALL.xlsx n'est plus complété ligne à ligne (il se remplissait
%    de doublons à chaque relance) : analyse_assembly_results6 le réécrit
%    entièrement à partir des resume_K de toutes les sessions et de tous les K
%  - sce_n_cells_threshold = seuil réellement utilisé (avant : opts écrasé
%    par SCE_detection4, même valeur)
%  - colonnes en plus : session, K, faux SCE attendus par hasard
%  - chemins avec fullfile (avant : '\analysis.xlsx' ne marchait pas sur Mac)

opts = P.opts;
speed = double(P.speed(:)');
[NCell, Nz] = size(P.Tr1b);
WinRest = P.WinRest;
sampling_rate = P.sampling_rate;

average_speed = round(mean(speed(speed > 2)), 2);
max_speed     = max(speed);
freqsce       = round(A.NRace / length(WinRest) * sampling_rate, 2);
freqsceok     = round(A.NRaceOK / length(WinRest) * sampling_rate, 2);

idortho = cellfun(@length, A.assemblyortho);
writeassemblyortho = numel(A.assemblyortho);
mean_cell_assembly = mean(idortho);          % NaN s'il n'y a pas d'assemblée

% number of lap (même calcul qu'avant)
if isfield(P, 'position') && ~isempty(P.position)
    tmp = diff(double(P.position(:)'));
    [~, locs] = findpeaks(-tmp, 'MinPeakHeight', 10);
    nb_lap = length(locs);
else
    nb_lap = NaN;
end

% Silhouettes
if ~isempty(A.sCl), sil_all = mean(A.sCl); else, sil_all = NaN; end
if A.NClOK > 0, sil_ok = mean(A.sCl(1:A.NClOK)); else, sil_ok = NaN; end
if isfield(A, 'mean_Event_Purity'), SCE_Purity = A.mean_Event_Purity; else, SCE_Purity = NaN; end
if isfield(A, 'mean_Cellular_Fidelity'), cell_Purity = A.mean_Cellular_Fidelity; else, cell_Purity = NaN; end
if isfield(opts, 'sce_n_cells_threshold_calcule')
    sce_n_cells_threshold = opts.sce_n_cells_threshold_calcule;
else
    sce_n_cells_threshold = opts.sce_n_cells_threshold;
end

resume_K = struct( ...
    'date',                   datestr(now, 'yy_mm_dd_HH_MM_SS'), ...
    'identifier',             char(string(P.identifier)), ...
    'session',                session.nom, ...
    'NCl_ini',                A.NClini, ...
    'SCE',                    A.NRace, ...
    'sce_freq',               freqsce, ...
    'SCEok',                  A.NRaceOK, ...
    'SCEok_freq',             freqsceok, ...
    'Assemblies',             writeassemblyortho, ...
    'SCE_Purity',             SCE_Purity, ...
    'cell_Purity',            cell_Purity, ...
    'sil_all_clusters',       sil_all, ...
    'SClok',                  sil_ok, ...
    'SClokfinal',             A.mean_sClOK, ...
    'cell_assembly',          num2str(idortho), ...
    'mean_cell_assembly',     mean_cell_assembly, ...
    'Ncell',                  NCell, ...
    'frames',                 Nz, ...
    'sampling_rate',          sampling_rate, ...
    'nb_frame_not_running',   length(WinRest), ...
    'pct_not_running',        length(WinRest) / Nz * 100, ...
    'average_speed',          average_speed, ...
    'max_speed',              max_speed, ...
    'nblap',                  nb_lap, ...
    'sce_n_cells_threshold',  sce_n_cells_threshold, ...
    'faux_SCE_attendus',      P.diagnostic.n_SCE_hasard, ...
    'n_kmean_surrogate',      config.asm.kmeans_surrogate, ...
    'min_sce_distance',       opts.MinPeakDistancesce, ...
    'MinPeakDistance',        opts.MinPeakDistance, ...
    'synchronous_frames',     opts.synchronous_frames, ...
    'max_cells_SCE_allowed',  P.max_cells_allowed);

% Ligne écrite dans le dossier du K
pathexcel = fullfile(namefull, 'analysis.xlsx');
if isfile(pathexcel), delete(pathexcel); end
writetable(resume_vers_table(resume_K), pathexcel);
end


function T = resume_vers_table(resume)
% struct d'une ligne -> table d'une ligne (texte en cellules)
T = cell2table(struct2cell(resume)', 'VariableNames', fieldnames(resume)');
end
